// The PC port's platform layer (docs/port.md). Port code uses the host's headers and fixed-width
// types; the game's C (src/) is compiled with -DPLATFORM_PC and calls in through Port_Dma and
// Port_WaitVBlank.
#ifndef PORT_H
#define PORT_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>

// The GBA memory map, reserved at the same host addresses (port/src/memory.c).
#define EWRAM_START 0x02000000u
#define EWRAM_SIZE 0x40000u
#define IWRAM_START 0x03000000u
#define IWRAM_SIZE 0x8000u
#define IO_START 0x04000000u
#define IO_SIZE 0x1000u
#define PLTT_START 0x05000000u
#define PLTT_SIZE 0x400u
#define VRAM_START 0x06000000u
#define VRAM_SIZE 0x18000u
#define OAM_START 0x07000000u
#define OAM_SIZE 0x400u
#define ROM_START 0x08000000u
#define ROM_RESERVE 0x02000000u
#define ROM_SIZE 0x400000u
#define SRAM_START 0x0E000000u
#define SRAM_SIZE 0x10000u

#define BASEROM_SHA1 "6025ef597db2684ae064ffe22b4fd1d37941f887"

#define IO16(ofs) (*(volatile uint16_t *)(uintptr_t)(IO_START + (ofs)))
#define IO32(ofs) (*(volatile uint32_t *)(uintptr_t)(IO_START + (ofs)))

// port_tables.c (generated by port/tools/gen_port_tables.py)
struct PortRomPatch {
    uint32_t location;  // the ROM word
    uint32_t value;     // the original's value there (a GBA function address, bit 0 = Thumb)
    void (*func)(void); // the host function of the same name
};
struct PortFunction {
    uint32_t gbaAddress;  // bit 0 set for Thumb
    void (*func)(void);   // NULL when the port does not define it
    const char *name;
};
extern const struct PortRomPatch gPortRomPatches[];
extern const int gPortNumRomPatches;
extern const struct PortFunction gPortFunctions[];
extern const int gPortNumFunctions;

// memory.c
void Port_MapMemory(char **argv);
void Port_ClearMemory(void);
void Port_ProtectRom(void);

// rom.c
void Port_LoadRom(const char *path);
bool Port_HostToGba(uint32_t hostAddress, uint32_t *gbaAddress);

// sram.c
void Port_LoadSram(const char *path);
void Port_SaveSram(void);
void Port_SetSaveFile(const char *path);
void Port_SetDefaultSaveFile(void);  // kururin.sav next to the executable
void Port_SramFrame(void);           // after every frame: writes the save once SRAM settles

// hw.c
void Port_Dma(uint32_t dmaNum, const volatile void *src, volatile void *dest, uint32_t control);
void Port_RaiseIrq(uint16_t bit);
void Port_RunHblankDma(void);
// m4aSoundVSync (port/src/m4a_1.c) restarted the sound DMAs: they read from their source again
void Port_SoundDmaRestart(void);
// A sound FIFO (0: A, 1: B) asks for data: the 16 bytes the DMA channel feeding it moves, or
// false if none does
bool Port_SoundDmaRequest(uint32_t fifo, uint8_t out[16]);
void Port_WaitVBlank(void);

// video.c: the renderer. Port_DrawFrame runs the 160 lines of a frame (VCount matches, the
// HBlank DMA and interrupt between lines) and, if *draw*, draws them into gPortScreen: mGBA's
// colours, 0x00BBGGRR in the low 24 bits (the top byte holds the renderer's flags).
extern uint32_t gPortScreen[160 * 240];
void Port_DrawFrame(bool draw);

// divide.c: an integer division by 0 (or INT_MIN / -1) gives the GBA's libgcc result instead of trapping
void Port_InstallDivideHandler(void);

// apu.c: the GB-compatible channels
void Port_ApuSync(void);
void Port_ApuRun(uint32_t cycles, uint32_t sums[4]);
void Port_ApuReset(void);
void Port_ApuTrace(FILE *f, long frame);

// audio.c: the sound output. device: SDL audio; volume: percent; wavPath: also into a WAV file;
// only: "psg" or "ds" for the GB channels or DirectSound alone (a debugging aid), else NULL
void Port_AudioInit(bool device, int volume, const char *wavPath, const char *only, const char *psgTrace);
bool Port_AudioActive(void);
void Port_AudioFrame(void);                         // at each frame boundary, before the VBlank interrupt
int64_t Port_AudioPacing(uint64_t ticksPerFrame);  // the frame loop's adjustment
void Port_AudioReset(void);
void Port_AudioClose(void);

// config.c: kururin.ini (the window, the sound, pausing, the keys and the gamepad buttons)
#define PORT_NUM_BUTTONS 10  // the GBA's, in KEYINPUT's bit order: A B Select Start Right Left Up Down R L
void Port_LoadConfig(const char *path);  // NULL: kururin.ini next to the executable
uint16_t Port_KeyboardBits(void);         // the GBA buttons the keys held now press (KEYINPUT bits, active high)
uint16_t Port_GamepadBits(void *controller);  // the same for an SDL_GameController
uint16_t Port_KeyBits(int32_t key);             // the GBA buttons one key (an SDL_Keycode) is
uint16_t Port_GamepadButtonBits(int button);    // ... and one gamepad button (SDL_GameControllerButton)

// audio.c: pausing (the window lost the focus)
void Port_AudioPause(bool pause);

// frame.c: what happens at each frame boundary (inputs, dumps, the window)
struct PortOptions {
    const char *romPath;
    const char *inputsPath;
    const char *dumpPath;
    const char *watchPath;
    const char *lagPath;
    const char *savePath;
    const char *videoPath;  // the screen's hash every fbEvery frames (the pixel test)
    const char *shotDir;    // where --shot screenshots go
    long shots[64];
    int numShots;
    struct { long frame; uint32_t addr; uint8_t value; } pokes[64];  // --poke (debugging)
    int numPokes;
    int fbEvery;
    const char *wavPath;  // the sound output, also into this WAV file
    const char *soundOnly; // "psg" or "ds": only those (debugging)
    const char *psgTracePath; // the GB channels' state after each frame (debugging)
    int volume;       // percent (-1 until set: the command line, else kururin.ini, else 100)
    bool mute;
    int scale;        // the window: 240x160 times this (0 until set, as volume; default 3)
    int fullscreen;   // -1 until set (default 0)
    bool pauseOnFocusLoss;
    const char *configPath;  // --config (default: kururin.ini next to the executable)
    long frames;      // stop after this many frames (0: no limit)
    bool headless;
    bool noSave;      // no save file at all
};
extern struct PortOptions gPortOptions;
void Port_InitFrames(void);
void Port_StartFrame(void);
// At the frame boundary, before the VBlank interrupt (Port_WaitVBlank): first each lag frame
// the original had here (only with --lag-frames: true, its sample skipped, *irq whether its
// VBlank raised the interrupt), then the end of the frame: dump the watched RAM, show the
// window, and return the keys (KEYINPUT bits, active high) of the next frame. Exits after
// --frames frames or when the window is closed.
bool Port_LagFrame(bool *irq);
int Port_NextLagKind(void);  // the frame that ends next: 0 not a lag frame, 1 one, 2 one without its interrupt
bool Port_NextLagInMixer(void);  // and its VBlank came while the original's mixer ran
// The lag frame Port_LagFrame returned last: m4a's VSync ignored its VBlank in the original
// (m4a_1.c's m4aSoundVSync ignores it too while hw.c raises it)
extern bool gPortLagSoundOff;
extern bool gPortInLagVBlank;
// hw.c: the original's lag VBlanks of this frame of work: before the mixer (all but one that
// came during the mixing), or all
void Port_RunLagFrames(bool beforeMixer);
bool Port_WantPixels(void);
uint16_t Port_EndFrame(void);
_Noreturn void Port_Exit(int status);
// main.c: the console's reset: everything but the ROM and SRAM cleared, AgbMain again
_Noreturn void Port_Reset(void);

// The game's entry (src/main.c)
void AgbMain(void);

// mingw's C99 printf (__USE_MINGW_ANSI_STDIO) is checked as gnu_printf
#ifdef _WIN32
#define PORT_PRINTF gnu_printf
#else
#define PORT_PRINTF printf
#endif
void Port_Die(const char *fmt, ...) __attribute__((format(PORT_PRINTF, 1, 2), noreturn));

#endif
