#!/usr/bin/env python3
"""The Windows build's GBA memory, as part of the exe's own image (docs/port.md, "The memory map
on Windows: in the image").

The kernel maps an exe's image when it creates the process, before ntdll runs, before any DLL,
heap or thread stack exists. So the GBA's memory is made sections of kururin_pc.exe, at their
GBA addresses: uninitialised (nothing in the file), read-write where the GBA has memory, read-only
zeros in between (the open bus above the image's headers, the mirrors, the gaps), the exe's own
code and data after them, from 0x10000000. The image is based at 0x00400000 (the usual exe
base), without relocations or ASLR, so it is mapped there or not at all.

usage: win_image.py asm OUT.S             the sections (gas, .space in bss sections)
       win_image.py ld LD OUT.ld          LD's default script (LD --verbose) with the sections
                                          first and .text at 0x10000000
       win_image.py patch EXE             makes the filler sections read-only (gas has no flag for
                                          read-only uninitialised data) and checks that every
                                          region is in place: exits 1 if not
"""
import struct
import subprocess
import sys

IMAGE_BASE = 0x00400000
CODE = 0x10000000

# (section, start, end, writable): contiguous from IMAGE_BASE + 0x1000 to CODE, as PE sections
# must be (port/src/port.h has the same regions)
REGIONS = [
    (".gbabus", IMAGE_BASE + 0x1000, 0x02000000, False),  # the open bus after the headers
    (".ewram", 0x02000000, 0x02040000, True),
    (".ewmirr", 0x02040000, 0x03000000, False),
    (".iwram", 0x03000000, 0x03008000, True),
    (".iwmirr", 0x03008000, 0x04000000, False),
    (".gbaio", 0x04000000, 0x04001000, True),
    (".gap4", 0x04001000, 0x05000000, False),
    (".pltt", 0x05000000, 0x05001000, True),
    (".gap5", 0x05001000, 0x06000000, False),
    (".vram", 0x06000000, 0x06018000, True),
    (".gap6", 0x06018000, 0x07000000, False),
    (".oam", 0x07000000, 0x07001000, True),
    (".gap7", 0x07001000, 0x08000000, False),
    (".gbarom", 0x08000000, 0x0A000000, True),  # read-only once the ROM is loaded (memory.c)
    (".gap8", 0x0A000000, 0x0E000000, False),
    (".sram", 0x0E000000, 0x0E010000, True),
    (".gape", 0x0E010000, CODE, False),
]

SCN_UNINIT, SCN_READ, SCN_WRITE = 0x80, 0x40000000, 0x80000000


def write_asm(out):
    lines = ["/* Generated by port/tools/win_image.py: the GBA's memory as sections of the exe. */"]
    for name, start, end, _ in REGIONS:
        lines += [f"    .section {name},\"bw\"", f"    .space 0x{end - start:X}"]
    open(out, "w").write("\n".join(lines) + "\n")


def write_ld(ld, out):
    text = subprocess.run([ld, "--verbose"], check=True, capture_output=True, text=True).stdout
    script = text.split("=" * 50)[1].strip("\n")
    old = "  .text  __image_base__ + ( __section_alignment__ < 0x1000 ? . : __section_alignment__ ) :"
    if old not in script:
        sys.exit("win_image.py: the linker's default script has no .text line as expected")
    gba = "".join(f"  {name} 0x{start:08X} : {{ KEEP(*({name})) }}\n" for name, start, _, _ in REGIONS)
    script = script.replace(old, "  /* port/tools/win_image.py: the GBA's memory, then the exe */\n" + gba +
                            f"  .text 0x{CODE:08X} :")
    open(out, "w").write(script + "\n")


def patch(exe):
    data = bytearray(open(exe, "rb").read())
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    nsec, opt = struct.unpack_from("<H", data, pe + 6)[0], struct.unpack_from("<H", data, pe + 20)[0]
    base = struct.unpack_from("<I", data, pe + 24 + 28)[0]
    dllch = struct.unpack_from("<H", data, pe + 24 + 70)[0]
    errors = []
    if base != IMAGE_BASE:
        errors.append(f"image base 0x{base:08X}, not 0x{IMAGE_BASE:08X}")
    if dllch & 0x40:
        errors.append("ASLR (DYNAMICBASE) is on")
    sections = {}
    table = pe + 24 + opt
    for i in range(nsec):
        o = table + 40 * i
        name = data[o:o + 8].rstrip(b"\0").decode("latin-1")
        vsize, va, rawsize = struct.unpack_from("<III", data, o + 8)
        sections[name] = (o, base + va, vsize, rawsize)
    for name, start, end, writable in REGIONS:
        if name not in sections:
            errors.append(f"no section {name}")
            continue
        o, va, vsize, rawsize = sections[name]
        if va != start or (vsize + 0xFFF) & ~0xFFF != end - start or rawsize:
            errors.append(f"{name} at 0x{va:08X} size 0x{vsize:X} raw 0x{rawsize:X}, want 0x{start:08X}-0x{end:08X}, "
                          f"uninitialised")
        struct.pack_into("<I", data, o + 36, SCN_UNINIT | SCN_READ | (SCN_WRITE if writable else 0))
    if ".text" not in sections or sections[".text"][1] != CODE:
        errors.append(f".text not at 0x{CODE:08X}")
    if any(n == ".reloc" for n in sections):
        errors.append("the image has a .reloc section")
    if errors:
        sys.exit(f"win_image.py: {exe}: " + "; ".join(errors))
    open(exe, "wb").write(data)


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "asm" and len(sys.argv) == 3:
        write_asm(sys.argv[2])
    elif cmd == "ld" and len(sys.argv) == 4:
        write_ld(sys.argv[2], sys.argv[3])
    elif cmd == "patch" and len(sys.argv) == 3:
        patch(sys.argv[2])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
