#!/usr/bin/env python3
"""Generate the PC port's address tables (docs/port.md, "Function pointers in ROM data").

usage: gen_port_tables.py [--nm NM] [--prefix _] OUT_DIR OBJECT...

--nm: the objects' nm (default nm; i686-w64-mingw32-nm for the Windows build); --prefix: what the
compiler puts before a C name in the objects (32-bit Windows: "_"), so gba_symbols.ld defines
the names the objects use.

Writes, from kururin.toml, config/functions.txt and config/data_pointers.txt (no ROM content):

  OUT_DIR/gba_symbols.ld   PROVIDE(name = address) for every data symbol the objects leave
                           undefined: kururin.toml [symbols] (RAM and ROM data at the
                           original's addresses), the gUnk_<address> labels, and
                           [linker_constants] (numbers the original's linker script defined).
  OUT_DIR/port_tables.c    gPortRomPatches: each ROM word holding a code pointer (kind `code`)
                           and the host function of the same name, which the loader writes there;
                           gPortFunctions: every function of config/functions.txt with its GBA
                           address and host address (NULL when the objects do not define it),
                           to turn host function addresses back into GBA ones in RAM dumps;
                           empty stubs for the hand-written asm (crt0, m4a_1, libagbsyscall,
                           the [[asm_regions]]) that the objects (port/src) do not define.
                           (Plain definitions, read from the objects with nm: weak ones are not
                           resolved by GNU ld's PE target, the Windows build.)
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from generate_asm import load_config, function_names  # noqa: E402


def undefined_symbols(nm, prefix, objects):
    """The C names the objects leave undefined (without the compiler's prefix)."""
    out = subprocess.run([nm, "-u"] + objects, check=True, capture_output=True, text=True).stdout
    names = {l.split()[-1] for l in out.split("\n") if l.strip() and not l.endswith(":")}
    return sorted(n[len(prefix):] for n in names if n.startswith(prefix))


def defined_symbols(nm, prefix, objects):
    """The C names the objects define as global functions or data."""
    out = subprocess.run([nm, "--defined-only", "-g"] + objects, check=True, capture_output=True, text=True).stdout
    names = {l.split()[-1] for l in out.split("\n") if len(l.split()) == 3}
    return {n[len(prefix):] for n in names if n.startswith(prefix)}


def asm_ranges(cfg):
    """[start, end) of the code that is hand-written asm in the GBA build."""
    mods = cfg["modules"]
    ranges = []
    for i, m in enumerate(mods):
        if m["kind"] == "asm":
            ranges.append((m["start"], mods[i + 1]["start"]))
    for r in cfg.get("asm_regions", []):
        ranges.append((r["start"], r["end"]))
    return ranges


def lib_ranges(cfg):
    """[start, end) of libgcc and libc: the port uses the host's."""
    mods = cfg["modules"]
    return [(m["start"], mods[i + 1]["start"]) for i, m in enumerate(mods) if m["kind"] == "lib"]


def main():
    args, nm, prefix = sys.argv[1:], "nm", ""
    while args and args[0] in ("--nm", "--prefix"):
        if args[0] == "--nm":
            nm = args[1]
        else:
            prefix = args[1]
        args = args[2:]
    out_dir, objects = args[0], args[1:]
    cfg, funcs, _, _ = load_config()
    names = function_names(cfg, funcs)
    symbols = cfg.get("symbols", {})
    consts = {k: v["value"] for k, v in cfg.get("linker_constants", {}).items()}
    os.makedirs(out_dir, exist_ok=True)

    ld = ["/* Generated by port/tools/gen_port_tables.py -- do not edit. */"]
    missing = []
    for sym in undefined_symbols(nm, prefix, objects):
        if sym in symbols:
            ld.append(f"PROVIDE({prefix}{sym} = 0x{symbols[sym]:08X});")
        elif sym in consts:
            ld.append(f"PROVIDE({prefix}{sym} = {consts[sym]});")
        elif re.fullmatch(r"gUnk_[0-9A-F]{8}", sym):
            ld.append(f"PROVIDE({prefix}{sym} = 0x{sym[5:]});")
        else:
            missing.append(sym)  # functions and host library symbols: defined elsewhere
    with open(os.path.join(out_dir, "gba_symbols.ld"), "w") as f:
        f.write("\n".join(ld) + "\n")

    # code pointers in the ROM's data
    patches = []
    for line in open(os.path.join(ROOT, "config", "data_pointers.txt")):
        p = line.split("#", 1)[0].split()
        if len(p) >= 3 and p[2] == "code":
            loc, value = int(p[0], 16), int(p[1], 16)
            target = value & ~1
            if target not in names:
                sys.exit(f"data pointer at 0x{loc:08X}: 0x{value:08X} is not a function entry")
            patches.append((loc, value, names[target]))

    asm = asm_ranges(cfg)
    asm_funcs = sorted(a for a in names if any(lo <= a < hi for lo, hi in asm))
    c = ["/* Generated by port/tools/gen_port_tables.py from kururin.toml, config/functions.txt and",
         " * config/data_pointers.txt -- do not edit. Addresses only: no ROM content. */",
         "#include \"port.h\"",
         ""]
    defined = defined_symbols(nm, prefix, objects)
    c.append("/* The hand-written asm (crt0, m4a_1, libagbsyscall, [[asm_regions]]): an empty stub for")
    c.append(" * each function port/src does not define itself. */")
    for a in asm_funcs:
        if names[a] in defined:
            c.append(f"extern void {names[a]}(void);")
        else:
            c.append(f"void {names[a]}(void) {{ }}")
            defined.add(names[a])
    c.append("")
    lib = lib_ranges(cfg)
    names = {a: n for a, n in names.items() if not any(lo <= a < hi for lo, hi in lib)}
    for a in sorted(names):
        if names[a] in defined and not any(lo <= a < hi for lo, hi in asm):
            c.append(f"extern void {names[a]}(void);")
    c.append("")
    c.append("const struct PortRomPatch gPortRomPatches[] = {")
    for loc, value, name in patches:
        c.append(f"    {{ 0x{loc:08X}, 0x{value:08X}, {name} }},")
    c.append("};")
    c.append(f"const int gPortNumRomPatches = {len(patches)};")
    c.append("")
    c.append("const struct PortFunction gPortFunctions[] = {")
    for a in sorted(names):
        thumb = funcs[a] == "thumb"
        func = names[a] if names[a] in defined else "NULL"
        c.append(f"    {{ 0x{a | thumb:08X}, {func}, \"{names[a]}\" }},")
    c.append("};")
    c.append(f"const int gPortNumFunctions = {len(names)};")
    with open(os.path.join(out_dir, "port_tables.c"), "w") as f:
        f.write("\n".join(c) + "\n")


if __name__ == "__main__":
    main()
